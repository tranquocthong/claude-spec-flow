test('TC-008: direct array response → tasks written to tasks.json with status pending', async () => {
  const tmpDir = makeTmpDir();
  const _paths = makePaths(tmpDir);
  const tag = 'tc008-direct';

  const tasks = [
    makeValidTask({ id: '1', title: 'Task one' }),
    makeValidTask({ id: '2', title: 'Task two' }),
  ];

  const { _httpPost } = makeHttpPostInjectDirect(tasks);

  const result = await provider.execute(
    'parse-prd',
    makeParams(tag),
    makeFallbackConfig(),
    { _httpPost, _paths }
  );

  assert.ok(result && typeof result === 'object', 'execute must return an object');
  assert.equal(result.imported, 2, 'result.imported must equal number of tasks');

  // Verify tasks were actually written to tasks.json
  const stored = JSON.parse(fs.readFileSync(_paths.tasksFile, 'utf8'));
  const tagData = stored[tag];
  assert.ok(tagData, 'Tag namespace must exist in tasks.json');
  assert.ok(Array.isArray(tagData.tasks), 'tasks must be an array');
  assert.equal(tagData.tasks.length, 2, 'tasks.json must contain 2 tasks');

  // All statuses must be normalized to 'pending' (importTasks guarantee)
  for (const t of tagData.tasks) {
    assert.equal(t.status, 'pending',
      `Task ${t.id} status must be 'pending' after import (TC-008)`);
  }
});

