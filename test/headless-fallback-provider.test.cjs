/**
 * Unit tests for lib/headless-fallback-provider.cjs — HeadlessFallbackProvider.
 *
 * All tests use an injected _httpPost function to avoid real network calls (NFR-002).
 * All writes use injected _paths for filesystem isolation (os.mkdtemp).
 *
 * Covers:
 *   TC-008: injected _httpPost returns valid task JSON array → tasks written via importTasks,
 *           all status 'pending', no error; execute() returns { imported: N }.
 *   TC-009 (light): null fallbackConfig → throws before any transport is invoked.
 *   authorization header: _httpPost receives Authorization: Bearer <apiKey> in headers.
 *   missing fallbackConfig fields: each of endpoint/model/apiKey missing → throws.
 *   non-2xx response (status 401/500) → throws ERR_AI_FALLBACK_FAILED.
 *   invalid JSON in choices content → throws ERR_AI_FALLBACK_FAILED.
 *   response has no tasks → throws ERR_AI_FALLBACK_FAILED.
 *   response with tasks at data.tasks (flat object) → imported correctly.
 *   response with tasks at data.choices[0].message.content JSON → imported correctly.
 *   no real network calls: injected _httpPost is the only transport.
 *
 * Run: node test/headless-fallback-provider.test.cjs
 */
