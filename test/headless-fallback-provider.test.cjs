function makeTmpDir() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'hfp-test-'));
}

function makePaths(tmpDir) {
  return {
    tasksFile: path.join(tmpDir, '.taskmaster', 'tasks', 'tasks.json'),
  };
}

/** Build a minimal valid fallbackConfig object. */
function makeFallbackConfig(overrides) {
  return Object.assign(
    {
      endpoint: 'https://api.example.com/v1/chat/completions',
      model: 'gpt-4o',
      apiKey: 'sk-test-key-12345',
    },
    overrides
  );
}

/**
 * Build a schema-valid task object that importTasks will accept without error.
 * All 8 required fields are present.
 */
function makeValidTask(overrides) {
  return Object.assign(
    {
      id: '1',
      title: 'Task from LLM',
      description: 'A task generated by the LLM.',
      status: 'pending',
      priority: 'medium',
      dependencies: [],
      subtasks: [],
      updatedAt: '2026-07-26T00:00:00.000Z',
    },
    overrides
  );
}

/**
 * Build a minimal params object for execute().
 * execute(op, params, fallbackConfig, _inject)
 */
function makeParams(tag, overrides) {
  return Object.assign({ tag: tag || 'test-tag' }, overrides);
}

/**
 * Create an injected _httpPost that returns a direct task array (data is Array).
 * Returns { captured } so tests can inspect what was passed to _httpPost.
 */
function makeHttpPostInjectDirect(tasks) {
  const captured = { calls: [] };
  const _httpPost = async (url, options) => {
    captured.calls.push({ url, options });
    return { status: 200, json: tasks };
  };
  return { _httpPost, captured };
}

/**
 * Create an injected _httpPost that returns { tasks: [...] } (data.tasks).
 */
function makeHttpPostInjectDataTasks(tasks) {
  const captured = { calls: [] };
  const _httpPost = async (url, options) => {
    captured.calls.push({ url, options });
    return { status: 200, json: { tasks } };
  };
  return { _httpPost, captured };
}

/**
 * Create an injected _httpPost that returns an OpenAI-shaped response
 * where the tasks array is JSON-encoded in choices[0].message.content.
 */
function makeHttpPostInjectChoices(tasks) {
  const captured = { calls: [] };
  const _httpPost = async (url, options) => {
    captured.calls.push({ url, options });
    return {
      status: 200,
      json: {
        choices: [
          { message: { content: JSON.stringify(tasks) } },
        ],
      },
    };
  };
  return { _httpPost, captured };
}

/**
 * Create an injected _httpPost that returns a non-2xx status.
 */
function makeHttpPostInjectError(status, body) {
  const _httpPost = async () => ({ status, json: body });
  return { _httpPost };
}

