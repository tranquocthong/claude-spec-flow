test('Authorization header contains Bearer <apiKey> (injected _httpPost receives it)', async () => {
  const tmpDir = makeTmpDir();
  const _paths = makePaths(tmpDir);
  const tag = 'tag-auth-check';
  const apiKey = 'sk-secret-key-9876';

  const tasks = [makeValidTask({ id: '1', title: 'Auth check task' })];
  const { _httpPost, captured } = makeHttpPostInjectDirect(tasks);

  await provider.execute(
    'parse-prd',
    makeParams(tag),
    makeFallbackConfig({ apiKey }),
    { _httpPost, _paths }
  );

  assert.equal(captured.calls.length, 1, '_httpPost must be called exactly once');
  const { options } = captured.calls[0];
  assert.ok(options && options.headers, '_httpPost must receive an options.headers object');

  const authHeader = options.headers['Authorization'] || options.headers['authorization'];
  assert.ok(authHeader, 'Authorization header must be present in _httpPost call');
  assert.ok(
    authHeader === `Bearer ${apiKey}`,
    `Authorization must be "Bearer ${apiKey}"; got: "${authHeader}"`
  );
});

