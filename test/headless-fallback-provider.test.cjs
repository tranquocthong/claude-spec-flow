test('no real network calls: execute only uses the injected _httpPost transport', async () => {
  // This test confirms that when _httpPost is injected, no real fetch() is called.
  // We verify this by using a fake _httpPost that tracks calls — if fetch() were
  // called without injection, it would fail (fetch not available in test env or
  // would require real network). The injected transport is the only path.
  const tmpDir = makeTmpDir();
  const _paths = makePaths(tmpDir);
  const tasks = [makeValidTask({ id: '1', title: 'No-network task' })];

  let httpCalled = false;
  const _httpPost = async () => {
    httpCalled = true;
    return { status: 200, json: tasks };
  };

  await provider.execute(
    'parse-prd',
    makeParams('tag-no-network'),
    makeFallbackConfig(),
    { _httpPost, _paths }
  );

  assert.ok(httpCalled, 'injected _httpPost must have been called');
  // If we reach here without an unhandled real fetch error, the injected path works.
});

